from datetime import date, datetime
from typing import Annotated, Literal
from uuid import UUID

from pydantic import Field, model_validator

from app.core.api import ApiModel
from app.models.enums import IssueSeverity, IssueStatus, IssueType


class GeoPoint(ApiModel):
    type: Literal["Point"]
    coordinates: tuple[
        Annotated[float, Field(ge=-180, le=180, allow_inf_nan=False)],
        Annotated[float, Field(ge=-90, le=90, allow_inf_nan=False)],
    ]


class IssueCreate(ApiModel):
    asset_id: UUID
    type: IssueType = IssueType.OUTAGE_REPORT
    region_id: UUID | None = None
    segment_id: UUID | None = None
    subregion_id: UUID | None = None
    file_id: UUID | None = None
    meter_id: UUID | None = None
    client_id: UUID | None = None
    video_inspection_id: UUID | None = None
    video_offset_seconds: int | None = Field(default=None, ge=0)
    location: GeoPoint
    description: str | None = None
    severity: IssueSeverity

    @model_validator(mode="after")
    def validate_video_offset(self):
        if self.video_offset_seconds is not None and self.video_inspection_id is None:
            raise ValueError("videoOffsetSeconds requires videoInspectionId")
        if self.type in (IssueType.ML_FORECAST, IssueType.MISSING_DOCUMENTS):
            raise ValueError("This issue type is generated by the backend")
        if self.segment_id and self.subregion_id and self.segment_id != self.subregion_id:
            raise ValueError("segmentId and subregionId must agree")
        return self


class IssueStatusUpdate(ApiModel):
    status: IssueStatus
    assigned_team_label: str | None = Field(default=None, max_length=128)
    version: int = Field(ge=1)


class IssueResource(ApiModel):
    id: UUID
    type: IssueType
    title: str
    is_historical: bool
    region_id: UUID | None
    segment_id: UUID | None = None
    file_id: UUID | None
    meter_id: UUID | None
    client_id: UUID | None
    case_id: UUID | None
    forecast_date: date | None
    subregion_id: UUID | None = None
    asset_id: UUID
    location: GeoPoint
    description: str | None
    severity: IssueSeverity
    status: IssueStatus
    assigned_team_label: str | None
    created_at: datetime
    resolved_at: datetime | None
    version: int
